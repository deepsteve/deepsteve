// Unit tests for superviews — a selectable project view's `cards` (and its sibling flag,
// `launcher`). Three halves:
//
//   - the view file: `launcher` / `cards` are kept on a view you look at, dropped on an additive
//     one, round-trip through the file, and go out on the wire;
//   - the server's prompt source (mods/project-mods/view-cards.js) and its route,
//     GET /api/project-views/cards: the first REAL prompt of a Claude transcript — never a slash
//     command, a meta caveat or a sidechain — cached once found, re-read until then;
//   - the client (public/js/view-cards.js): the superview at the head of the strip, the grid it
//     opens, the cards' prompts, and when the grid goes down.
//
// No browser, no daemon: the client half runs against stubbed DOM globals and a fake fetch, and
// the module is re-imported with a unique ?query per test so its state starts fresh.
//
// Run: node --test test/unit/view-cards.test.js

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const HOME = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-view-cards-home-'));
process.env.HOME = HOME;

const views = require('../../mods/project-mods/tools.js');
const { normalizeView, serializeView, viewManifestOf } = views;
const { createPromptSource, firstPrompt, PROMPT_CHARS } = require('../../mods/project-mods/view-cards.js');
const { normalizeLines } = require('../../transcript-view');

const REPO = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ds-view-cards-repo-')));
const TRANSCRIPTS = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-view-cards-transcripts-'));

// ------------------------------------------------------------------- view file

test('launcher and cards are kept on a view you look at, and dropped on an additive one', () => {
  const v = normalizeView({ name: 'Analytics', icon: '📈', launcher: true, cards: true }, REPO, 'analytics');
  assert.strictEqual(v.launcher, true);
  assert.strictEqual(v.cards, true);
  assert.deepStrictEqual(viewManifestOf(v), { name: 'Analytics', icon: '📈', match: [], launcher: true, cards: true }, 'written back as read');
  const wire = serializeView(v);
  assert.strictEqual(wire.launcher, true);
  assert.strictEqual(wire.cards, true);

  const add = normalizeView({ name: 'GitHub', additive: true, launcher: true, cards: true }, REPO, 'github');
  assert.strictEqual(add.launcher, false, 'an additive view is never selected, so it has nothing to launch into');
  assert.strictEqual(add.cards, false);
  assert.ok(!('launcher' in viewManifestOf(add)));

  const plain = normalizeView({ name: 'Plain', launcher: 'yes', cards: 1 }, REPO, 'plain');
  assert.strictEqual(plain.launcher, false, 'only a literal true');
  assert.strictEqual(plain.cards, false);
  assert.deepStrictEqual(viewManifestOf(plain), { name: 'Plain', match: [] }, 'false flags are left out of the file');
});

// ------------------------------------------------------------ the first prompt

const line = (o) => JSON.stringify(o);
const user = (content, extra = {}) => line({ type: 'user', message: { role: 'user', content }, ...extra });
const assistant = (text) => line({ type: 'assistant', message: { role: 'assistant', id: 'm1', content: [{ type: 'text', text }] } });

function transcript(name, lines) {
  const file = path.join(TRANSCRIPTS, `${name}.jsonl`);
  fs.writeFileSync(file, lines.join('\n') + '\n');
  return file;
}

const entriesOf = (lines) => normalizeLines({ lines: lines.map((text, i) => ({ offset: i, bytes: 1, text })) }).entries;

test('firstPrompt skips machinery: caveats, slash commands, sidechains, compactions, tool results', () => {
  const lines = [
    line({ type: 'permission-mode', mode: 'default' }),
    user('Caveat: The messages below were generated by the user while running local commands.', { isMeta: true }),
    user('<command-name>/rc</command-name>\n<command-message>rc</command-message>'),
    user('<local-command-stdout>Remote control on</local-command-stdout>'),
    user('a subagent prompt', { isSidechain: true }),
    user('This session is being continued from a previous conversation…', { isCompactSummary: true }),
    user([{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }]),
    user([{ type: 'image', source: { media_type: 'image/png', data: 'AAAA' } }, { type: 'text', text: '  What was D7 retention for Off Leash last week?  ' }]),
    assistant('Let me check.'),
    user('a second prompt'),
  ];
  assert.strictEqual(firstPrompt(entriesOf(lines)), 'What was D7 retention for Off Leash last week?');
  assert.strictEqual(firstPrompt(entriesOf(lines.slice(0, 7))), null, 'nothing anyone typed');
  assert.strictEqual(firstPrompt([]), null);
});

test('firstPrompt clips a long prompt to PROMPT_CHARS', () => {
  const long = 'x'.repeat(PROMPT_CHARS * 2);
  const got = firstPrompt(entriesOf([user(long)]));
  assert.strictEqual(got.length, PROMPT_CHARS);
  assert.ok(got.endsWith('…'));
});

const CLAUDE = { supportsSessionWatch: true };
const CODEX = { supportsSessionWatch: false };
const agentConfig = (t) => (t === 'codex' ? CODEX : CLAUDE);

test('promptFor reads the transcript, caches a found prompt, and re-reads until there is one', async () => {
  const file = path.join(TRANSCRIPTS, 'later.jsonl');
  const paths = { s1: file };
  const src = createPromptSource({ transcriptPath: (e) => paths[e.id] || null, getAgentConfig: agentConfig });

  assert.deepStrictEqual(await src.promptFor({ id: 's1' }), { prompt: null, supported: true }, 'no file yet: never prompted');

  transcript('later', [user('<command-name>/rc</command-name>')]);
  assert.deepStrictEqual(await src.promptFor({ id: 's1' }), { prompt: null, supported: true }, 'only machinery so far');

  transcript('later', [user('<command-name>/rc</command-name>'), user('Funnel from install to first walk?')]);
  assert.deepStrictEqual(await src.promptFor({ id: 's1' }), { prompt: 'Funnel from install to first walk?', supported: true });

  // Found prompts are kept: rewriting the file behind its back changes nothing.
  transcript('later', [user('something else')]);
  assert.strictEqual((await src.promptFor({ id: 's1' })).prompt, 'Funnel from install to first walk?');

  assert.deepStrictEqual(await src.promptFor({ id: 's2' }), { prompt: null, supported: true }, 'no transcript path at all');
  assert.deepStrictEqual(await src.promptFor({ id: 's1', agentType: 'codex' }), { prompt: null, supported: false }, 'an agent with no transcript');
});

test('promptFor reads past a head with no prompt in it, window by window, and stops at the cap', async () => {
  const reads = [];
  const pages = [
    { lines: [{ offset: 0, bytes: 10, text: user('<command-name>/rc</command-name>') }], size: 100, nextAfter: 10 },
    { lines: [{ offset: 10, bytes: 10, text: user('the real one') }], size: 100, nextAfter: 20 },
  ];
  const src = createPromptSource({
    transcriptPath: () => '/fake',
    getAgentConfig: agentConfig,
    readWindow: async (file, { after }) => { reads.push(after); return pages[reads.length - 1]; },
  });
  assert.strictEqual((await src.promptFor({})).prompt, 'the real one');
  assert.deepStrictEqual(reads, [0, 10]);

  let n = 0;
  const endless = createPromptSource({
    transcriptPath: () => '/fake2',
    getAgentConfig: agentConfig,
    readWindow: async () => { n++; return { lines: [], size: 1e9, nextAfter: n * 10 }; },
  });
  assert.strictEqual((await endless.promptFor({})).prompt, null);
  assert.strictEqual(n, 4, 'bounded: a session with no prompt in its head is not read to the end');
});

test('GET /api/project-views/cards answers each id from its session', async () => {
  const fileA = transcript('route-a', [user('Which ad set drives installs?')]);
  const shells = new Map([
    ['a', { id: 'a', cwd: REPO, agentType: 'claude' }],
    ['c', { id: 'c', cwd: REPO, agentType: 'codex' }],
  ]);
  const ctx = {
    shells,
    settings: { projectModsEnabled: true },
    reloadClients: new Set(),
    log: () => {},
    broadcast: () => {},
    getContexts: () => [],
    transcriptPath: (e) => (e.id === 'a' ? fileA : null),
    getAgentConfig: agentConfig,
  };
  views.init(ctx);
  const routes = new Map();
  views.registerRoutes({
    get: (p, h) => routes.set(`GET ${p}`, h), post: (p, h) => routes.set(`POST ${p}`, h),
    put: (p, h) => routes.set(`PUT ${p}`, h), delete: (p, h) => routes.set(`DELETE ${p}`, h),
  }, ctx);
  const res = { statusCode: 200, body: null };
  res.status = (c) => { res.statusCode = c; return res; };
  res.json = (v) => { res.body = v; return res; };
  await routes.get('GET /api/project-views/cards')({ query: { ids: 'a,c,gone,a' }, params: {} }, res);
  assert.strictEqual(res.statusCode, 200);
  assert.deepStrictEqual(res.body.prompts, {
    a: { prompt: 'Which ad set drives installs?', supported: true },
    c: { prompt: null, supported: false },
    gone: { prompt: null, supported: false },
  });
});

// ------------------------------------------------------------------ the client

function fakeElement(tag = 'div') {
  const classes = new Set();
  let children = [];
  let text = '';
  const el = {
    tag, id: '', title: '', style: {}, dataset: {}, attrs: {}, listeners: {},
    get children() { return children; },
    get parentNode() { return el.parent || null; },
    get isConnected() { return !!el.parent; },
    classList: {
      add: (c) => classes.add(c),
      remove: (c) => classes.delete(c),
      contains: (c) => classes.has(c),
      toggle: (c, force) => {
        const on = force === undefined ? !classes.has(c) : !!force;
        on ? classes.add(c) : classes.delete(c);
        return on;
      },
    },
    addEventListener: (ev, fn) => { el.listeners[ev] = fn; },
    append: (...kids) => { for (const k of kids) el.appendChild(k); },
    appendChild: (child) => { child.parent = el; children.push(child); return child; },
    insertBefore: (child, ref) => {
      const i = ref ? children.indexOf(ref) : -1;
      children.splice(i === -1 ? children.length : i, 0, child);
      child.parent = el;
      return child;
    },
    replaceChildren: (...kids) => { children = []; for (const k of kids) el.appendChild(k); },
    setAttribute: (k, v) => { el.attrs[k] = String(v); },
    blur: () => { el.blurred = true; },
  };
  Object.defineProperty(el, 'className', {
    get: () => [...classes].join(' '),
    set: (v) => { classes.clear(); for (const c of String(v).split(/\s+/).filter(Boolean)) classes.add(c); },
  });
  Object.defineProperty(el, 'textContent', {
    get: () => text + children.map(c => c.textContent).join(''),
    set: (v) => { text = String(v); children = []; },
  });
  return el;
}

const byId = new Map();
const root = fakeElement('body');
root.parent = {};
globalThis.document = {
  getElementById: (id) => byId.get(id) || null,
  createElement: (tag) => fakeElement(tag),
  activeElement: null,
};
// The grid polls while it is up; the test runs the poll by hand.
const timers = new Set();
globalThis.setInterval = (fn) => { const t = { fn }; timers.add(t); return t; };
globalThis.clearInterval = (t) => { timers.delete(t); };

const CTX = { id: 'ctx1', name: 'Off Leash', dirs: ['/repo/offleash'] };
const ANALYTICS = { slug: 'analytics', name: 'Analytics', icon: '📈', launcher: true, cards: true };
const flush = () => new Promise(r => setTimeout(r, 0));
let importCount = 0;

/**
 * Fresh module + DOM. `state` is what the callbacks read and record: the active project, its
 * selected view, the tabs in it, what the server answers, and every open / strip / footer call.
 */
async function setup({ view = ANALYTICS, tabs = [], answers = {} } = {}) {
  byId.clear();
  timers.clear();
  root.children.length = 0;
  const wrapper = fakeElement();
  root.appendChild(wrapper);
  const toggle = fakeElement('button');
  toggle.id = 'views-toggle';
  const slot = fakeElement();
  slot.id = 'tab-slot';
  const list = fakeElement();
  wrapper.append(toggle, slot, list);
  const terminals = fakeElement();
  root.appendChild(terminals);
  byId.set('tabs-list-wrapper', wrapper);
  byId.set('tabs-list', list);
  byId.set('tab-slot', slot);
  byId.set('terminals', terminals);
  const xterm = fakeElement('textarea');
  document.activeElement = xterm;

  const state = { ctx: CTX, view, tabs, answers, fetches: [], opened: [], strip: [], upChanges: 0, fail: false };
  globalThis.fetch = async (url) => {
    state.fetches.push(url);
    if (state.fail) return { ok: false, status: 500, json: async () => ({ error: 'boom' }) };
    const ids = decodeURIComponent(url.split('ids=')[1]).split(',');
    const prompts = {};
    for (const id of ids) prompts[id] = state.answers[id] || { prompt: null, supported: true };
    return { ok: true, status: 200, json: async () => ({ prompts }) };
  };
  const mod = await import(`../../public/js/view-cards.js?t=${++importCount}`);
  mod.init({
    getActiveContext: () => state.ctx,
    cardsFor: (ctx) => (ctx ? state.view : null),
    cardTabs: () => state.tabs,
    openTab: (id) => state.opened.push(id),
    setStripActive: (on) => state.strip.push(on),
    onUpChanged: () => state.upChanges++,
  });
  const superview = () => byId.get('tabs-list-wrapper').children.find(c => c.id === 'view-cards-tab');
  const pane = () => terminals.children.find(c => c.id === 'view-cards');
  return { mod, state, wrapper, slot, list, terminals, xterm, superview, pane };
}

const cardsIn = (pane) => {
  const grid = pane.children.find(c => c.className === 'view-cards-grid');
  return grid ? grid.children : [];
};

test('the superview sits after the views toggle and before the slot, only while its view is selected', async () => {
  const { mod, state, wrapper, slot, superview } = await setup({ tabs: [{ id: 't1', name: 'Retention' }, { id: 't2', name: 'Ads' }] });
  const el = superview();
  assert.ok(el, 'drawn');
  assert.deepStrictEqual(wrapper.children.map(c => c.id), ['views-toggle', 'view-cards-tab', 'tab-slot', ''], 'toggle, superview, slot, tabs');
  assert.ok(!el.classList.contains('hidden'));
  assert.ok(el.classList.contains('tab'), 'looks like a tab');
  const [icon, , label, count] = el.children;
  assert.strictEqual(icon.textContent, '▦', 'the grid mark, not the emoji #views-toggle already shows');
  assert.strictEqual(label.textContent, 'Analytics');
  assert.strictEqual(count.textContent, '2');
  assert.ok(slot.parentNode === wrapper);

  state.view = null;   // All selected, or a view without cards
  mod.render();
  assert.ok(el.classList.contains('hidden'));
});

test('opening the superview puts the grid up: cards with first prompts, no active tab, terminal blurred', async () => {
  const { mod, state, superview, pane, xterm } = await setup({
    tabs: [{ id: 't1', name: 'Retention', current: true }, { id: 't2', name: 'Ads' }, { id: 't3', name: 'Codex' }],
    answers: {
      t1: { prompt: 'What was D7 retention last week?', supported: true },
      t3: { prompt: null, supported: false },
    },
  });
  superview().listeners.click();
  assert.ok(mod.isUp());
  assert.deepStrictEqual(state.strip, [false], 'no real tab reads as active under the grid');
  assert.ok(xterm.blurred, 'keys can no longer reach the terminal underneath');
  assert.strictEqual(state.upChanges, 1, 'the footer is told');
  assert.ok(superview().classList.contains('active'));
  assert.ok(!pane().classList.contains('hidden'));

  let cards = cardsIn(pane());
  assert.deepStrictEqual(cards.map(c => c.children[1].textContent), ['Loading…', 'Loading…', 'Loading…'], 'before the answer');
  await flush(); await flush();
  assert.strictEqual(state.fetches.length, 1, 'one request for every card');
  assert.match(state.fetches[0], /^\/api\/project-views\/cards\?ids=t1,t2,t3$/);

  cards = cardsIn(pane());
  assert.deepStrictEqual(cards.map(c => c.children[0].textContent), ['Retention', 'Ads', 'Codex']);
  assert.deepStrictEqual(cards.map(c => c.children[1].textContent), [
    'What was D7 retention last week?',
    'No prompt yet',
    'This agent keeps no transcript to read a prompt from',
  ]);
  assert.ok(cards[0].className.includes('current'));
  assert.ok(cards[1].children[1].className.includes('empty'));

  // The poll asks again only about the tab that may still get one.
  state.answers.t2 = { prompt: 'Which ad set drives installs?', supported: true };
  for (const t of timers) await t.fn();
  await flush();
  assert.match(state.fetches[1], /ids=t2$/);
  assert.strictEqual(cardsIn(pane())[1].children[1].textContent, 'Which ad set drives installs?');

  // Nothing left to learn: the poll sends nothing.
  for (const t of timers) await t.fn();
  assert.strictEqual(state.fetches.length, 2);

  cardsIn(pane())[1].listeners.click();
  assert.deepStrictEqual(state.opened, ['t2'], 'a card opens its tab');
});

test('the grid goes down on a tab switch, and when its view or project stops being selected', async () => {
  const { mod, state, superview, pane } = await setup({ tabs: [{ id: 't1', name: 'Retention' }] });
  superview().listeners.click();
  await flush();
  assert.strictEqual(timers.size, 1, 'polling while up');

  mod.dismiss();   // app.js's switchTo()
  assert.ok(!mod.isUp());
  assert.ok(pane().classList.contains('hidden'));
  assert.ok(!superview().classList.contains('active'));
  assert.deepStrictEqual(state.strip, [false, true], 'the active tab is marked again');
  assert.strictEqual(timers.size, 0, 'no poll while down');
  mod.dismiss();
  assert.deepStrictEqual(state.strip, [false, true], 'a second dismiss is a no-op');

  superview().listeners.click();
  state.ctx = { id: 'ctx2', name: 'McHoops', dirs: ['/repo/mchoops'] };   // another project, same view slug
  mod.render();
  assert.ok(!mod.isUp(), 'the grid belongs to the project it was opened in');

  superview().listeners.click();
  state.view = null;   // the view was switched to All
  mod.render();
  assert.ok(!mod.isUp());
  assert.ok(superview().classList.contains('hidden'));
  assert.ok(pane().classList.contains('hidden'));
});

test('an empty view says how to start a tab in it; a failed fetch stops saying Loading…', async () => {
  const { state, superview, pane } = await setup({ tabs: [] });
  superview().listeners.click();
  const empty = pane().children.find(c => c.className === 'view-cards-empty');
  assert.match(empty.textContent, /New Analytics tab/);
  assert.strictEqual(state.fetches.length, 0, 'nothing to ask about');

  const s2 = await setup({ tabs: [{ id: 't1', name: 'Retention' }] });
  s2.state.fail = true;
  s2.superview().listeners.click();
  await flush(); await flush();
  assert.strictEqual(cardsIn(s2.pane())[0].children[1].textContent, 'No prompt yet');
  assert.strictEqual(s2.state.fetches.length, 1, 'no retry storm: the next try is the poll');
  s2.mod.dismiss();
});

